#!/usr/bin/env python3
"""Deterministic line-of-code count for one repository at one commit.

Usage:
  loc.py <git-dir> <sha> [--repo NAME] [--fork-base SHA] [--scc PATH] [--out FILE]

Only the tracked blobs of <sha> are counted, read raw from the object store
(no checkout, no .gitignore, no line-ending filters), so two machines with the
same pinned scc get the same bytes out. Omega (.om) is counted here because scc
has no Omega definition: a line is blank when it holds only whitespace, a
comment when its first word is `note`, and code otherwise.

Every file is put in exactly one category:
  first_party  - our own source
  vendored     - copied third-party code (vendor/, third_party/, linguist-vendored, ...)
  generated    - machine-written files (generated markers, linguist-generated, lockfiles, *.min.*)
  evidence     - recorded run artifacts under evidence/ or receipts/ trees
The rules are in RULES below and in classify.json (per-repository additions).
"""
import argparse, fnmatch, hashlib, json, os, re, subprocess, sys, tempfile

TOOL_VERSION = "aien-audit-loc/2"

# Languages that are data, markup, prose or styling, not executable code.
NON_EXECUTABLE = {
    "JSON", "JSONL", "JSONC", "YAML", "TOML", "INI", "XML", "SVG", "HTML", "XHTML", "CSS", "SCSS", "Sass", "LESS",
    "Markdown", "Plain Text", "Text", "ReStructuredText", "AsciiDoc", "Org", "TeX", "LaTeX", "BibTeX",
    "CSV", "TSV", "License", "gitignore", "gitattributes", "Gitignore", "Docker ignore", "Properties File",
    "Jupyter", "Patch", "Diff", "Unknown", "Protocol Buffers", "Cap'n Proto", "Device Tree", "Rich Text Format",
    "Wiki", "Systemd", "Hex", "Intel HEX", "Mustache", "Handlebars", "Jinja", "Twig", "Liquid",
}
VENDOR_DIRS = {"vendor", "vendored", "third_party", "third-party", "thirdparty", "3rdparty", "node_modules",
               "external", "extern", "deps", "bower_components", ".cargo-vendor"}
EVIDENCE_DIRS = {"evidence", "receipts"}
GENERATED_NAMES = {"Cargo.lock", "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "uv.lock",
                   "Pipfile.lock", "go.sum", "composer.lock", "Gemfile.lock", "bun.lockb", "flake.lock"}
GENERATED_GLOBS = ["*.min.js", "*.min.css", "*.min.mjs", "*.map", "*.pb.go", "*_pb2.py"]
GENERATED_MARKER = re.compile(rb"(@generated|do not edit|auto-generated|autogenerated|code generated by)", re.I)

SCC_FLAGS = ["--no-ignore", "--no-gitignore", "--no-gitmodule", "--no-scc-ignore", "--no-config",
             "--no-cocomo", "--no-complexity", "--no-size", "--by-file", "--format", "json",
             "--exclude-file", "", "--count-as-pattern", "*.osc:OSC (legacy Omega):Rust"]


def git(gd, *args, inp=None):
    return subprocess.run(["git", "-C", gd, *args], input=inp, capture_output=True, check=True).stdout


def tree_entries(gd, sha):
    out = git(gd, "ls-tree", "-r", "-z", "--full-tree", sha)
    for rec in out.split(b"\0"):
        if not rec:
            continue
        meta, path = rec.split(b"\t", 1)
        mode, typ, oid = meta.split(b" ")
        yield mode.decode(), typ.decode(), oid.decode(), path.decode("utf-8", "surrogateescape")


def attrs(gd, sha, paths):
    if not paths:
        return {}
    inp = "\0".join(paths).encode("utf-8", "surrogateescape") + b"\0"
    out = git(gd, "check-attr", "-z", "--source", sha, "--stdin", "linguist-vendored", "linguist-generated",
              "linguist-documentation", inp=inp)
    f = out.split(b"\0")
    res = {}
    for i in range(0, len(f) - 2, 3):
        p, a, v = f[i].decode("utf-8", "surrogateescape"), f[i + 1].decode(), f[i + 2].decode()
        if v in ("set", "true"):
            res.setdefault(p, set()).add(a)
    return res


def classify(path, head, attr, extra):
    parts = path.split("/")
    for rule in extra:
        if fnmatch.fnmatchcase(path, rule["glob"]):
            return rule["category"], "classify.json: " + rule["reason"]
    if "linguist-vendored" in attr:
        return "vendored", ".gitattributes linguist-vendored"
    if "linguist-generated" in attr:
        return "generated", ".gitattributes linguist-generated"
    for d in parts[:-1]:
        if d in VENDOR_DIRS:
            return "vendored", "directory " + d + "/"
    for d in parts[:-1]:
        if d in EVIDENCE_DIRS:
            return "evidence", "directory " + d + "/"
    name = parts[-1]
    if name in GENERATED_NAMES:
        return "generated", "lockfile"
    for g in GENERATED_GLOBS:
        if fnmatch.fnmatchcase(name, g):
            return "generated", "pattern " + g
    if GENERATED_MARKER.search(head):
        return "generated", "generated marker in first 5 lines"
    return "first_party", ""


def count_omega(data):
    blank = comment = code = 0
    for line in data.split(b"\n") if data else []:
        s = line.strip()
        if not s:
            blank += 1
        elif s.split(None, 1)[0] == b"note":
            comment += 1
        else:
            code += 1
    if data.endswith(b"\n"):
        blank -= 1  # the empty string after the final newline is not a line
    return blank, comment, code


def materialize(gd, entries, root):
    oids = [e[2] for e in entries]
    if not oids:
        return {}
    heads = {}
    # a file, not a pipe: writing every request first would deadlock on large trees
    with tempfile.TemporaryFile() as req:
        req.write(("\n".join(oids) + "\n").encode())
        req.seek(0)
        with subprocess.Popen(["git", "-C", gd, "cat-file", "--batch"], stdin=req, stdout=subprocess.PIPE) as p:
            for (_, _, oid, path) in entries:
                hdr = p.stdout.readline().split()
                if len(hdr) != 3 or hdr[0].decode() != oid:
                    raise ValueError("git cat-file: %s for %s" % (b" ".join(hdr).decode(errors="replace"), path))
                data = p.stdout.read(int(hdr[2]))
                p.stdout.read(1)
                full = os.path.join(root, path)
                os.makedirs(os.path.dirname(full), exist_ok=True)
                with open(full, "wb") as fh:
                    fh.write(data)
                heads[path] = (b"\n".join(data.split(b"\n", 5)[:5]), data if path.endswith(".om") else None)
    if p.returncode != 0:
        raise ValueError("git cat-file exit %d" % p.returncode)
    return heads


def run_scc(scc, root):
    out = subprocess.run([scc, *SCC_FLAGS, root], capture_output=True, check=True).stdout
    per_file = {}
    for lang in json.loads(out or b"[]"):
        for f in lang.get("Files") or []:
            rel = os.path.relpath(f["Location"], root)
            per_file[rel] = (lang["Name"], f["Blank"], f["Comment"], f["Code"])
    return per_file


def scc_version(scc):
    return subprocess.run([scc, "--version"], capture_output=True, text=True).stdout.strip()


def fork_added_lines(gd, base, sha, paths):
    """Non-blank lines added by our commits to each modified upstream file (git diff -U0, no renames)."""
    if not paths:
        return {}
    out = git(gd, "-c", "core.quotePath=false", "diff", "--no-renames", "--no-color", "--no-ext-diff", "-U0",
              "--src-prefix=a/", "--dst-prefix=b/", base, sha, "--", *[":(literal)" + p for p in paths])
    counts, cur, in_header = {}, None, False
    for line in out.split(b"\n"):
        if line.startswith(b"diff --git "):
            in_header, cur = True, None
        elif in_header and line.startswith(b"+++ "):
            name = line[4:].rstrip(b"\t")  # git appends a tab to names that contain a space
            cur = None if name == b"/dev/null" else name[2:].decode("utf-8", "surrogateescape")
            if cur is not None:
                counts.setdefault(cur, 0)
        elif line.startswith(b"@@"):
            in_header = False
        elif not in_header and line.startswith(b"+") and cur is not None and line[1:].strip():
            counts[cur] += 1
    return counts


def org_totals(docs):
    """Org-wide totals over per-repository results. `distinct` counts each blob once across repositories,
    so code copied between repositories is not counted twice."""
    total = {"repositories": len(docs), "first_party_executable_code": 0, "first_party_code_all": 0,
             "distinct_first_party_executable_code": 0, "distinct_first_party_code_all": 0, "by_language": {}}
    seen = set()
    for d in sorted(docs, key=lambda d: d["repository"]):
        for f in d["files"]:
            if f["category"] != "first_party":
                continue
            total["first_party_code_all"] += f["code"]
            if f["executable"]:
                total["first_party_executable_code"] += f["code"]
            # a fork-modified file's count is a diff, not the blob's content, so it is never deduplicated
            key = (f["blob"], f["language"]) if not f.get("fork_modified") else (d["repository"], f["path"])
            if key in seen:
                continue
            seen.add(key)
            total["distinct_first_party_code_all"] += f["code"]
            if f["executable"]:
                total["distinct_first_party_executable_code"] += f["code"]
                bl = total["by_language"].setdefault(f["language"], 0)
                total["by_language"][f["language"]] = bl + f["code"]
    total["by_language"] = dict(sorted(total["by_language"].items(), key=lambda kv: (-kv[1], kv[0])))
    return total


def count(gd, sha, repo, fork_base, scc, extra):
    sha = git(gd, "rev-parse", sha + "^{commit}").decode().strip()
    tree = git(gd, "rev-parse", sha + "^{tree}").decode().strip()
    entries, skipped = [], {"gitlink": 0, "symlink": 0, "binary_or_unknown_language": 0}
    for mode, typ, oid, path in tree_entries(gd, sha):
        if typ == "commit":
            skipped["gitlink"] += 1
        elif mode == "120000":
            skipped["symlink"] += 1
        else:
            entries.append((mode, typ, oid, path))
    changed, added_lines = None, {}
    if fork_base:
        fork_base = git(gd, "rev-parse", fork_base + "^{commit}").decode().strip()
        diff = git(gd, "diff", "--no-renames", "-z", "--name-status", fork_base, sha).split(b"\0")
        changed = {}
        for i in range(0, len(diff) - 1, 2):
            st = diff[i].decode()
            if st and st[0] in "AM":
                changed[diff[i + 1].decode("utf-8", "surrogateescape")] = st[0]
        entries = [e for e in entries if e[3] in changed]
        added_lines = fork_added_lines(gd, fork_base, sha, sorted(p for p, s in changed.items() if s == "M"))
    oids = {e[3]: e[2] for e in entries}
    paths = [e[3] for e in entries]
    at = attrs(gd, sha, paths)
    with tempfile.TemporaryDirectory(prefix="aien-loc-") as root:
        heads = materialize(gd, entries, root)
        per_file = run_scc(scc, root)
    files = []
    for p in sorted(paths):
        head, omdata = heads[p]
        if p.endswith(".om"):
            b, c, k = count_omega(omdata)
            lang = ("Omega", b, c, k)
        else:
            lang = per_file.get(p)
        if lang is None:
            skipped["binary_or_unknown_language"] += 1
            continue
        cat, why = classify(p, head, at.get(p, set()), extra)
        name, b, c, k = lang
        rec = {"path": p, "blob": oids[p], "language": name, "category": cat, "reason": why,
               "code": k, "comment": c, "blank": b, "executable": name not in NON_EXECUTABLE}
        if fork_base and changed.get(p) == "M":
            # A diff hunk has no language context, so comments cannot be told from code here:
            # count every non-blank line our commits added to the upstream file.
            rec.update({"code": added_lines.get(p, 0), "comment": 0, "blank": 0, "fork_modified": True})
        files.append(rec)
    summary = {}
    for f in files:
        cat = summary.setdefault(f["category"], {"files": 0, "code_executable": 0, "code_all": 0, "by_language": {}})
        cat["files"] += 1
        cat["code_all"] += f["code"]
        if f["executable"]:
            cat["code_executable"] += f["code"]
        bl = cat["by_language"].setdefault(f["language"], {"files": 0, "code": 0, "comment": 0, "blank": 0,
                                                            "executable": f["executable"]})
        bl["files"] += 1
        bl["code"] += f["code"]
        bl["comment"] += f["comment"]
        bl["blank"] += f["blank"]
    result = {
        "schema": "aien-audit-loc/2",
        "repository": repo,
        "commit": sha,
        "tree": tree,
        "mode": "fork-diff" if fork_base else "full-tree",
        "fork_base": fork_base,
        "tools": {"counter": TOOL_VERSION, "scc": scc_version(scc)},
        "definition": "code = lines that are neither blank nor comment; executable = language not in NON_EXECUTABLE "
                      "(data, markup, prose, styling); Omega .om counted by this script (comment = first word `note`)."
                      + (" Fork mode: files we added count in full; for upstream files we modified, code = non-blank "
                         "lines added relative to the upstream merge-base (comments included, deletions not subtracted)."
                         if fork_base else ""),
        "skipped": skipped,
        "first_party_executable_code": summary.get("first_party", {}).get("code_executable", 0),
        "categories": summary,
        "files": files,
    }
    return result


def canonical(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode() + b"\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("gitdir")
    ap.add_argument("sha")
    ap.add_argument("--repo", default="")
    ap.add_argument("--fork-base", default="")
    ap.add_argument("--scc", default=os.environ.get("SCC", "scc"))
    ap.add_argument("--classify", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "classify.json"))
    ap.add_argument("--out", default="-")
    a = ap.parse_args()
    extra = []
    if os.path.exists(a.classify):
        extra = json.load(open(a.classify)).get(a.repo, [])
    res = count(a.gitdir, a.sha, a.repo, a.fork_base, a.scc, extra)
    data = canonical(res)
    if a.out == "-":
        sys.stdout.buffer.write(data)
    else:
        with open(a.out, "wb") as fh:
            fh.write(data)
    print(json.dumps({"repository": a.repo, "commit": res["commit"], "first_party_executable_code":
                      res["first_party_executable_code"], "sha256": hashlib.sha256(data).hexdigest()}), file=sys.stderr)


if __name__ == "__main__":
    main()
